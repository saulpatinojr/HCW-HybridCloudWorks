/**
 * The parts the AWS and GCP landing-zone packs share: how a pinned registry
 * module is written down (registryModule.js), the order the files are emitted
 * in, and the README that lists them. Each provider folder supplies only what
 * differs.
 */
import { isSelected, normalizeState } from '../state';
import { file } from './format';

export { registryModule } from './registryModule.js';

/**
 * Emit one provider's pack for a builder state: `terraform.tf` and
 * `providers.tf` always, one file per selected component, then variables,
 * the tfvars example and a README that lists what was emitted. A state with
 * nothing selected yields the README alone, which says so.
 *
 * @param {object} state the builder state `normalizeState` accepts
 * @param {object} pack the provider's emitters
 * @param {Array<[string, () => object]>} pack.components a component id and the file it adds, in emit order
 * @param {(state: object) => object} pack.workloads the spoke or project file, added when `corp` or `online` is selected
 * @returns {Array<{ path: string, content: string }>} the files, in emit order
 */
export function emitCloudPack(state, pack) {
  const normalized = normalizeState(state);
  if (!normalized.selected.length) return [pack.readme(normalized, [])];

  const files = [pack.terraform(), pack.providers()];

  for (const [component, emit] of pack.components) {
    if (isSelected(normalized, component)) files.push(emit());
  }
  if (isSelected(normalized, 'corp') || isSelected(normalized, 'online')) {
    files.push(pack.workloads(normalized));
  }

  files.push(pack.variables(normalized), pack.tfvars(normalized));
  files.push(pack.readme(normalized, files));
  return files;
}

/**
 * The pack's README.md.
 *
 * @param {object} readme
 * @param {string} readme.title the first heading
 * @param {string} readme.summary one sentence on what the pack deploys
 * @param {Array<{ path: string }>} readme.files the files emitted before it
 * @param {Array<[string, { source: string, version: string }]>} readme.modules a table label and its pinned module
 * @param {string} readme.terraformVersion the Terraform engine constraint
 * @param {string} readme.providerLine the provider requirement, as one Markdown list item
 * @param {string[]} readme.guardrails the guardrail list items
 * @param {string[]} [readme.sections] extra Markdown lines placed before the guardrails
 */
export function cloudReadme({
  title,
  summary,
  files,
  modules,
  terraformVersion,
  providerLine,
  guardrails,
  sections = [],
}) {
  const fileList = files.map((f) => `- \`${f.path}\``).join('\n');

  const lines = [
    `# ${title}`,
    '',
    'This infrastructure code was synthesized by the **HybridCloudWorks Multi-Cloud Landing Zone Builder**.',
    summary,
    '',
    '## Synthesized Files',
    '',
    fileList || '- None (empty selection)',
    '',
    '## Pinned Architecture Modules',
    '',
    `| Module | Registry Source | Pinned Version |`,
    `| :--- | :--- | :--- |`,
    ...modules.map(
      ([label, module]) => `| **${label}** | \`${module.source}\` | \`${module.version}\` |`
    ),
    '',
    '## Provider & Engine Requirements',
    '',
    `- **Terraform Engine**: \`${terraformVersion}\``,
    providerLine,
    '',
    '## Validation Quickstart',
    '',
    '```bash',
    '# Initialize required providers without backend lock',
    'terraform init -backend=false',
    '',
    '# Validate syntax and configuration integrity',
    'terraform validate',
    '```',
    '',
    ...sections,
    '## Security & Governance Guardrails',
    '',
    ...guardrails,
    '',
    '*Generated by Hybrid Cloud Works.*',
  ];

  return file('README.md', lines);
}
